import Foundation
import PadelStorage
import os

/// Приём матчей с часов — сторона телефона.
///
/// Всё, что телефон делает с приехавшим матчем, — записывает его к себе.
/// Экрану истории (тикеты 11, 12) он потом достанется из хранилища, а не
/// отсюда: матч приезжает в приложение, разбуженное системой ради него
/// одного, и никакого экрана в этот момент может не быть.
///
/// Один и тот же матч приезжает дважды, если часы не дождались подтверждения.
/// Второй приезд не заводит второй матч: хранилище узнаёт его по
/// идентификатору и обновляет запись — тем же журналом, если он не менялся, и
/// продолженным, если после доставки отменили очко и доиграли.
public final class MatchReception: Sendable {
    private let store: any MatchStore

    public init(store: any MatchStore, receiver: any MatchReceiver) {
        self.store = store

        receiver.onArrival { match in
            do {
                try store.save(match)
            } catch {
                // Второй попытки не будет: транспорт подтверждает доставку
                // приложению, а не удачную запись, и часы к этому моменту уже
                // сняли матч с очереди. Матч при этом не пропал — он остаётся
                // на часах, которые и есть источник правды (ADR-0002), — но в
                // истории его сегодня не окажется.
                logger.error("Приехавший матч не сохранён: \(error.localizedDescription)")
            }
        }
    }
}

private let logger = Logger(subsystem: "com.vveidi.padel", category: "delivery")
