/// Одна игра от первого розыгрыша до момента, когда набор правил объявляет её
/// законченной.
///
/// Матч — это набор правил, журнал розыгрышей и пометка недоигранности,
/// больше ничего: счёт и исход вычисляются из них каждый раз заново
/// (ADR-0001).
public struct Match: Equatable, Sendable {
    public let ruleset: Ruleset

    /// Сторона, подававшая первый розыгрыш. Свойство матча, а не набора
    /// правил: правила помнятся до следующего матча, а очередь подачи
    /// разыгрывается заново каждый раз. Спросит её стартовый экран (тикет 06).
    public let firstServer: Side

    public private(set) var journal: RallyJournal

    /// Прекращён ли матч досрочно.
    ///
    /// Единственное, что о матче приходится хранить помимо журнала, и потому
    /// не нарушение ADR-0001, а его граница: счёт из журнала вычисляется, а
    /// решение уйти с корта — нет. Журнал одинаков у матча, прекращённого при
    /// 5:2, и у матча, который вот-вот продолжат.
    public private(set) var isAbandoned: Bool

    public init(
        ruleset: Ruleset,
        firstServer: Side = .us,
        journal: RallyJournal = RallyJournal(),
        isAbandoned: Bool = false
    ) {
        self.ruleset = ruleset
        self.firstServer = firstServer
        self.journal = journal
        self.isAbandoned = isAbandoned
    }

    /// Счёт, подача и исход матча по текущему журналу.
    ///
    /// Пометка накладывается поверх посчитанного, а не подмешивается в счёт:
    /// движок остаётся чистой функцией от набора правил и журнала, а
    /// недоигранный матч сохраняет тот счёт, на котором его прекратили.
    public var state: MatchState {
        let state = MatchState(ruleset: ruleset, journal: journal, firstServer: firstServer)

        return isAbandoned ? state.abandoned : state
    }

    /// Записывает розыгрыш, выигранный указанной стороной.
    ///
    /// В законченном матче не делает ничего: касание экрана после последнего
    /// розыгрыша не должно ни менять счёт, ни отодвигать отмену (тикет 05)
    /// на лишние нажатия. Прекращённый досрочно — тот же случай: игра в нём
    /// кончилась, хоть победителя и нет.
    public mutating func record(rallyWonBy side: Side) {
        guard !state.outcome.isOver else { return }

        journal.append(wonBy: side)
    }

    /// Отменяет последний розыгрыш.
    ///
    /// Обратной арифметики здесь нет и быть не может: журнал укорачивается,
    /// а счёт, геймы, сеты и подающая сторона пересчитываются из того, что
    /// осталось (ADR-0001). Поэтому отмена одинаково проходит границу гейма,
    /// сета и тай-брейка — границы существуют только в свёртке.
    ///
    /// Законченный матч не исключение: отмена и нужна затем, чтобы вернуть
    /// в игру матч, законченный по ошибке. Прекращённый досрочно — исключение,
    /// и единственное: прекращение не розыгрыш, отменой очка оно не снимается,
    /// а укорачивать журнал матча, который уже помечен недоигранным, значило бы
    /// менять его счёт, ничего не возвращая в игру. От случайного касания
    /// прекращение защищено подтверждением, а не отменой.
    ///
    /// На пустом журнале не делает ничего.
    public mutating func undo() {
        guard !isAbandoned else { return }

        journal.removeLast()
    }

    /// Прекращает матч досрочно: кончилось время корта, пошёл дождь, кто-то
    /// потянул спину.
    ///
    /// Час игры при этом не пропадает — матч остаётся ровно тем, чем был, и
    /// сохраняется наравне с остальными, но помеченным. В законченном матче
    /// не делает ничего: у него уже есть победитель, и объявлять его
    /// недоигранным значило бы отменить его исход.
    public mutating func abandon() {
        guard !state.outcome.isOver else { return }

        isAbandoned = true
    }
}
